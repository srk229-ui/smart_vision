#ifndef LOCAL_BUTTONS_H
#define LOCAL_BUTTONS_H

#include <stdint.h>

#define LOCAL_BUTTON_EVENT_START (1u) // KEY1 本次确认按下产生的启动事件；与停止事件互斥。
#define LOCAL_BUTTON_EVENT_STOP (2u) // KEY2 本次确认按下产生的停止事件；双键同时按下时优先返回。

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化本地启动和停止按键的消抖状态
// 参数说明     void
// 返回参数     void
// 备注信息     开启扫描中断前调用；两个按键均须连续释放两次后才能产生首次按下事件
//-------------------------------------------------------------------------------------------------------------------
void local_buttons_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     每五毫秒扫描一次本地按键并返回本次确认的按下事件
// 参数说明     start_pressed   KEY1 电平已转换的按下标志，非零为按下
// 参数说明     stop_pressed    KEY2 电平已转换的按下标志，非零为按下
// 返回参数     uint8_t         0 表示无事件，否则为 LOCAL_BUTTON_EVENT_START 或 LOCAL_BUTTON_EVENT_STOP
// 备注信息     按下和释放均连续两次确认；停止按下或尚未确认释放时禁止启动，模块不访问硬件或控制状态
//-------------------------------------------------------------------------------------------------------------------
uint8_t local_buttons_scan(uint8_t start_pressed, uint8_t stop_pressed);

#endif
